"""Catalog entries for a TriTrypDB release published on Zenodo.

TriTrypDB needs a login to download from, so a release is fetched by hand, staged in a
directory, deposited on Zenodo as one record, and then described here: one catalog entry
per genome, all pointing at that record. See ``leishref dev import-tritrypdb``.
"""

import re
from pathlib import Path
from typing import Optional

from leishref.checksums import genome_stats, md5_file
from leishref.chromosomes import get_taxid_from_species
from leishref.metadata import Genome, today_iso

DOWNLOAD_URL = "https://tritrypdb.org/common/downloads/release-{release}"
POLICY_URL = "https://veupathdb.org/veupathdb/app/static-content/data_license.html"

#: Sequence ontology term in a TriTrypDB FASTA header -> NCBI-style assembly level.
ASSEMBLY_LEVELS = {"chromosome": "Chromosome", "supercontig": "Scaffold", "contig": "Contig"}

#: Genus-level NCBI taxon for strains whose species isn't named (e.g. "Leishmania sp. Ghana").
GENUS_TAXON_ID = 5658

BHU1220_NOTE = (
    "TriTrypDB provides no GFF for this strain in release 71. The GFF here was generated by LeishRef "
    "(Liftoff, from the annotation of TriTrypDB-71_LdonovaniHU3); it is not a TriTrypDB product."
)


def fasta_header_info(fasta: Path) -> dict:
    """organism, assembly date and sequence-ontology term from a TriTrypDB FASTA's first header."""
    with open(fasta) as fh:
        header = fh.readline()
    fields = {}
    for part in header.lstrip(">").split(" | ")[1:]:
        key, _, value = part.strip().partition("=")
        fields[key] = value
    return {
        "organism": fields.get("organism", "").replace("_", " "),
        "version": fields.get("version"),
        "so": fields.get("SO", "").lower(),
    }


def species_and_strain(organism: str) -> tuple:
    """Split 'Leishmania major strain Friedlin' into ('Leishmania major', 'Friedlin').

    An unnamed species ('Leishmania sp. Ghana MHOM/GH/2012/GH5') keeps the word after 'sp.'
    in its species ('Leishmania sp. Ghana'), as the NCBI entries do, and the rest as the strain.
    """
    words = organism.split()
    cut = 3 if len(words) > 2 and words[1] == "sp." else 2
    species = " ".join(words[:cut])
    strain = " ".join(words[cut:])
    strain = re.sub(r"^strain\s+", "", strain)
    return species, strain or None


def entry_name(release, name: str) -> str:
    return f"TriTrypDB-{release}_{name}"


def build_genome(
    release, name: str, directory: Path, doi: str, downloaded: str, gff_name: Optional[str] = None
) -> Genome:
    """The catalog entry for one genome of a release, measured from the staged files.

    ``name`` is TriTrypDB's own genome name ('LmajorFriedlin'). Its FASTA is
    ``TriTrypDB-<release>_<name>_Genome.fasta`` and its GFF ``TriTrypDB-<release>_<name>.gff``
    unless ``gff_name`` says otherwise (a GFF that isn't TriTrypDB's own).
    """
    directory = Path(directory)
    identifier = entry_name(release, name)
    fasta = f"{identifier}_Genome.fasta"
    gff = gff_name or f"{identifier}.gff"
    if not (directory / fasta).is_file():
        raise FileNotFoundError(directory / fasta)
    has_gff = (directory / gff).is_file()

    info = fasta_header_info(directory / fasta)
    species, strain = species_and_strain(info["organism"])
    taxon_id = get_taxid_from_species(species) or (GENUS_TAXON_ID if " sp. " in species else None)

    files = {"fasta": fasta}
    checksums = {"fasta": md5_file(directory / fasta)}
    if has_gff:
        files["gff"] = gff
        checksums["gff"] = md5_file(directory / gff)

    provenance = {"original_source": "TriTrypDB", "zenodo_doi": doi}
    notes = f"TriTrypDB release {release} genome, redistributed unmodified on Zenodo (see the license block)."
    if has_gff and gff_name:
        provenance["annotation_source"] = "Liftoff from TriTrypDB-71_LdonovaniHU3 (LeishRef)"
        notes += " " + BHU1220_NOTE

    return Genome(
        identifier=identifier,
        source="TriTrypDB",
        taxon_id=taxon_id,
        species=species,
        strain=strain,
        assembly_level=ASSEMBLY_LEVELS.get(info["so"]),
        release_date=info["version"],
        files=files,
        checksums=checksums,
        stats=genome_stats(directory / fasta),
        provenance=provenance,
        tritrypdb={
            "release": int(release),
            "source_url": DOWNLOAD_URL.format(release=release),
            "downloaded": downloaded,
        },
        license={
            "name": "VEuPathDB data access policy",
            "url": POLICY_URL,
            "note": "Freely available for public use; cite the original publications and VEuPathDB.",
        },
        access={"downloadable": True},
        date_added=today_iso(),
        notes=notes,
    )


def genome_names(directory: Path, release) -> list:
    """TriTrypDB genome names found in a staged release directory, from its *_Genome.fasta files."""
    prefix, suffix = f"TriTrypDB-{release}_", "_Genome.fasta"
    return sorted(p.name[len(prefix) : -len(suffix)] for p in Path(directory).glob(f"{prefix}*{suffix}"))
